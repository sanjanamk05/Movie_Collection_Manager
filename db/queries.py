"""SQL queries used by the movie collection manager."""

from __future__ import annotations

import sqlite3
from contextlib import contextmanager
from typing import Any, Iterator

from config.database import get_connection


@contextmanager
def _database_connection() -> Iterator[sqlite3.Connection]:
    """Open a database connection and ensure it is always closed.

    Yields:
        sqlite3.Connection: An active SQLite connection.
    """
    connection = get_connection()
    try:
        yield connection
    finally:
        connection.close()


def _row_to_dict(row: Any) -> dict[str, Any]:
    """Normalize database rows from SQLite results or test doubles.

    Args:
        row: A SQLite row, dict-like object, or object with attributes.

    Returns:
        dict[str, Any]: A standard dictionary representation of the row.
    """
    if row is None:
        return {}
    if isinstance(row, dict):
        return dict(row)
    if hasattr(row, "keys"):
        return dict(row)
    if hasattr(row, "__dict__"):
        return vars(row)
    return dict(row)


def add_movie(movie_name: str, genre: str, rating: float, release_year: int) -> int:
    """Insert a new movie record into the database.

    Args:
        movie_name: The movie title.
        genre: The movie genre.
        rating: The numeric rating value.
        release_year: The release year.

    Returns:
        int: The autogenerated movie id.

    Raises:
        RuntimeError: If the insert operation fails.
    """
    try:
        with _database_connection() as connection:
            cursor = connection.execute(
                """
                INSERT INTO movies (movie_name, genre, rating, release_year)
                VALUES (?, ?, ?, ?)
                """,
                (movie_name, genre, rating, release_year),
            )
            return int(cursor.lastrowid)
    except sqlite3.Error as exc:
        raise RuntimeError("Failed to insert movie record.") from exc


def fetch_movies() -> list[dict[str, Any]]:
    """Fetch all movies ordered by movie name and release year.

    Returns:
        list[dict[str, Any]]: Movie records as dictionaries.
    """
    try:
        with _database_connection() as connection:
            cursor = connection.execute(
                """
                SELECT movie_id, movie_name, genre, rating, release_year
                FROM movies
                ORDER BY movie_name ASC, release_year DESC
                """
            )
            rows = cursor.fetchall()
            return [_row_to_dict(row) for row in rows]
    except sqlite3.Error as exc:
        raise RuntimeError("Failed to retrieve movie records.") from exc


def fetch_average_rating() -> float | None:
    """Calculate the average rating of all stored movies.

    Returns:
        float | None: The average rating, or ``None`` when no movies exist.
    """
    try:
        with _database_connection() as connection:
            row = connection.execute(
                "SELECT AVG(rating) AS average_rating FROM movies"
            ).fetchone()
            row_dict = _row_to_dict(row)
            value = row_dict.get("average_rating") if row_dict else None
            return float(value) if value is not None else None
    except sqlite3.Error as exc:
        raise RuntimeError("Failed to calculate average rating.") from exc


def fetch_highest_rated_movie() -> dict[str, Any] | None:
    """Return the top-rated movie in the collection.

    Returns:
        dict[str, Any] | None: A movie dictionary if found, otherwise ``None``.
    """
    try:
        with _database_connection() as connection:
            row = connection.execute(
                """
                SELECT movie_id, movie_name, genre, rating, release_year
                FROM movies
                ORDER BY rating DESC, movie_id ASC
                LIMIT 1
                """
            ).fetchone()
            return _row_to_dict(row) if row is not None else None
    except sqlite3.Error as exc:
        raise RuntimeError("Failed to determine the highest rated movie.") from exc


def fetch_genre_summary() -> list[dict[str, Any]]:
    """Aggregate movies by genre and calculate average rating.

    Returns:
        list[dict[str, Any]]: Genre summary rows.
    """
    try:
        with _database_connection() as connection:
            rows = connection.execute(
                """
                SELECT genre,
                       COUNT(*) AS movie_count,
                       AVG(rating) AS average_rating
                FROM movies
                GROUP BY genre
                ORDER BY movie_count DESC, genre ASC
                """
            ).fetchall()
            return [_row_to_dict(row) for row in rows]
    except sqlite3.Error as exc:
        raise RuntimeError("Failed to generate genre summary.") from exc
